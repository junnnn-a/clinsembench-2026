#!/usr/bin/env python
"""
22_probe_public_suites.py — surface-only probe + meaning-blind baselines on a PUBLIC suite (10/7 review, point 1).

RaTE-Eval (Zhao et al., EMNLP 2024; HF Angelakeke/RaTE-Eval, CC-BY-4.0):
  Task 3 (synthetic): 847 triplets (original, synonym rewrite, opposite rewrite), generated by Mixtral-8x7B from
          MIMIC-IV report sentences. The release contains the rewrites and the opposites but not the originals;
          the originals are sentences of Task 1 (`gt_report_{train,test}.json`). We recover them by lexical matching
          (TF-IDF cosine to BOTH the rewrite and the opposite) and keep only confident matches.
          Protocol of the suite: a metric should score the synonym rewrite higher than the opposite.
  Task 1 (sentence level, radiologist error counts) and Task 2 (paragraph level, 0-5 radiologist score):
          how well do surface statistics alone predict the human rating? (Kendall tau), next to the meaning-blind
          baselines. This is the "surface-only regression" control for a human-rating benchmark.

Output: results/3_x3_audit/rate_eval_task3.csv, rate_eval_task12.csv, RATE_EVAL.md, data/external/rate_eval_task3_aligned.csv
Run: /opt/conda/envs/clinsev/bin/python scripts/22_probe_public_suites.py
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import kendalltau
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import Ridge
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import KFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

NEW = Path(__file__).resolve().parent.parent
B = NEW / "data/external/RaTE-Eval"
OUT = NEW / "results/3_x3_audit"
spec = importlib.util.spec_from_file_location("floor", NEW / "scripts/6_shortcut_floor.py")
F = importlib.util.module_from_spec(spec); spec.loader.exec_module(F)


def feats(refs, hyps):
    return pd.DataFrame([F.features(r, h) for r, h in zip(refs, hyps)])


def task3():
    rw = json.load(open(B / "Task3_synthetic_rate/rewrite_report.json"))
    op = json.load(open(B / "Task3_synthetic_rate/opposite_report.json"))
    gt = []
    for s in ["test", "train"]:
        gt += json.load(open(B / f"Task1_sentence_rate/gt_report_{s}.json"))
    gt = list(dict.fromkeys(gt))
    vec = TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True).fit(gt + rw + op)
    G, R, O = vec.transform(gt), vec.transform(rw), vec.transform(op)
    sr, so = (R @ G.T).toarray(), (O @ G.T).toarray()
    comb = np.minimum(sr, so) + 0.25 * (sr + so)
    idx = comb.argmax(1)
    df = pd.DataFrame({"original": [gt[i] for i in idx], "rewrite": rw, "opposite": op,
                       "sim_rewrite": sr[np.arange(len(rw)), idx], "sim_opposite": so[np.arange(len(rw)), idx]})
    # margin to the runner-up original -> confidence of the alignment
    part = np.partition(comb, -2, axis=1)
    df["margin"] = part[:, -1] - part[:, -2]
    df["confident"] = (df.sim_opposite >= 0.25) & (df.sim_rewrite >= 0.10) & (df.margin >= 0.05)
    # alignment check that cannot favour either candidate: the rewrite alone and the opposite alone pick the same original
    df["independent"] = sr.argmax(1) == so.argmax(1)
    df.to_csv(NEW / "data/external/rate_eval_task3_aligned.csv", index=False)
    # pairs file in the format of the scoring pipeline (run_set.sh rate3): P0 = synonym rewrite, C0 = opposite
    d = df[df.confident].reset_index()
    prs = []
    for r in d.itertuples():
        tid = f"rate3_{r.index}"
        base = dict(target_id=tid, corpus="rate3", report_id=str(r.index), section="sentence", edit_type="rate3", subtype="", pattern="",
                    edit_detail="", target_idx=0, needs_expert_review=False, reference=r.original)
        prs += [{"uid": f"{tid}__identity", **base, "cell": "identity", "surface_layer": "identity", "is_changed": 0, "candidate": r.original},
                {"uid": f"{tid}__P0", **base, "cell": "P0", "surface_layer": "S0", "is_changed": 0, "candidate": r.rewrite},
                {"uid": f"{tid}__C0", **base, "cell": "C0", "surface_layer": "S0", "is_changed": 1, "candidate": r.opposite}]
    pd.DataFrame(prs).to_csv(NEW / "data/pairs/full_rate3_all.csv", index=False)
    rows = []
    for name, d in [("all aligned", df), ("confident alignment", df[df.confident]), ("rewrite and opposite pick the same original", df[df.independent])]:
        long = pd.concat([pd.DataFrame({"reference": d.original, "candidate": d.rewrite, "is_changed": 0, "report_id": d.index}),
                          pd.DataFrame({"reference": d.original, "candidate": d.opposite, "is_changed": 1, "report_id": d.index})], ignore_index=True)
        X = feats(long.reference, long.candidate)
        y = long.is_changed.to_numpy()
        lr = F.cv_auc(X.to_numpy(), y, long.report_id.to_numpy())
        n = len(d)
        def pa(col):       # paired accuracy of a meaning-blind score: opposite penalised more than rewrite
            a, b = X[col].to_numpy()[n:], X[col].to_numpy()[:n]
            return float(np.mean((a > b) + 0.5 * (a == b)))
        rows.append({"subset": name, "n_triplets": n, "surface_only_LR_auroc": lr,
                     "auc_jaccard_drop": roc_auc_score(y, X.jaccard_drop), "auc_edit_tokens": roc_auc_score(y, X.edit_tokens),
                     "paired_acc_jaccard": pa("jaccard_drop"), "paired_acc_token_f1": pa("tokenf1_drop"), "paired_acc_edit_distance": pa("seq_ratio_drop"),
                     "mean_edit_frac_rewrite": float(X.edit_frac[:n].mean()), "mean_edit_frac_opposite": float(X.edit_frac[n:].mean())})
    T = pd.DataFrame(rows)
    T.to_csv(OUT / "rate_eval_task3.csv", index=False)
    return T, df


def task12():
    rows = []
    for task, f, ycol, higher_better in [("Task 1 (sentence, normalised error count)", "Task1_sentence_rate/rate_test.csv", "normalized", False),
                                         ("Task 2 (paragraph, 0-5 score)", "Task2_paragraph_rate/rate_test.csv", "Score", True)]:
        for split in ["test"]:
            d = pd.read_csv(B / f).dropna(subset=[ycol])
            tr = pd.read_csv(B / f.replace("test", "train")).dropna(subset=[ycol])
            Xte, Xtr = feats(d.gt_report, d.similar_report), feats(tr.gt_report, tr.similar_report)
            y, ytr = d[ycol].to_numpy(float), tr[ycol].to_numpy(float)
            sign = -1 if higher_better else 1        # features are "drops": larger = worse candidate
            model = make_pipeline(StandardScaler(), Ridge(alpha=1.0)).fit(Xtr.to_numpy(), ytr)
            pred = model.predict(Xte.to_numpy())
            r = {"task": task, "n_test": len(d), "surface_only_ridge_tau": kendalltau(pred, y).correlation}
            for c in ["jaccard_drop", "tokenf1_drop", "seq_ratio_drop", "char_ratio_drop", "edit_frac", "abs_len_diff"]:
                r[f"tau:{c}"] = sign * kendalltau(Xte[c], y).correlation
            rows.append(r)
    T = pd.DataFrame(rows)
    T.to_csv(OUT / "rate_eval_task12.csv", index=False)
    return T


def md(df, f=3):
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.{f}f}")
    cols = [str(c) for c in d.columns]
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"] +
                     ["| " + " | ".join(map(str, r)) + " |" for r in d.itertuples(index=False)])


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    T3, df = task3()
    T12 = pd.read_csv(OUT / "rate_eval_task12.csv") if (OUT / "rate_eval_task12.csv").exists() else task12()   # slow on long paragraphs; cached
    txt = ["# RaTE-Eval — surface-only probe (public suite)\n", "## Task 3 (synthetic triplets)\n", md(T3), "",
           f"alignment: {int(df.confident.sum())}/{len(df)} confident; examples:\n"]
    for r in df[df.confident].head(4).itertuples():
        txt.append(f"- ORIG: {r.original}\n  - REWRITE: {r.rewrite}\n  - OPPOSITE: {r.opposite}")
    txt += ["", "## Tasks 1-2 (radiologist ratings): Kendall tau of surface statistics with the human rating (sign fixed so that positive = agrees)\n", md(T12), ""]
    (OUT / "RATE_EVAL.md").write_text("\n".join(txt))
    print("\n".join(txt))
